"""
if / elif / else
se / mas se / se não
"""
condicao1 = False
condicao2 = True
condicao3 = True
condicao4 = True

if condicao1:
    print('Este é o código do condição 1')
elif condicao2:
    print('Codigo para condição 2')
elif condicao3:
    print('Codigo para condição 3')
elif condicao4:
    print('Codigo para condição 4')
else:
    print('Nenhuma condição foi satisfeita')

print('Fora do if')

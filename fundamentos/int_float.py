# Tipos primitivos.

"""
Tipos int e float
int = números inteiros
qualquer número que n tenha pontos
positivo ou negativo, int sem sinal é considerado positivo
"""
print(1, 2, 3) # int
print(-1, -2. -3) # int
print(0) # int

"""
float = o float é usado com números decimais
float = quaisquers números com pontos
float = sem sinal é positivo
"""
print(0.11, 0.2, 7.50) # float
print(0.0) # float
print(-1.5) # float

# A função type mostra qual o tipo primitivo.
print(type('João'))
print(type(1)) 
print(type(1.1))  
print(type(1), type(1.1), type('João'))